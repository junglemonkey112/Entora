 'FAFSA (Free Application for Federal Student Aid) — US Students

Required Documents
- Your Social Security Number
- Parents'' Social Security Numbers (if dependent student)
- Federal tax returns (yours and parents'') from 2 years prior
- Records of untaxed income (child support, veterans benefits, etc.)
- Bank account balances and investment records
- Records of any assets (businesses, farms — with exceptions)

Key Deadlines
- Federal deadline: June 30 each year
- State deadlines: vary widely — check your state''s deadline first
- College deadlines: often much earlier than federal/state — check each school''s financial aid page
- Best practice: submit by October 1 (the day FAFSA opens) for maximum aid consideration

CSS PROFILE — Required by ~250 Private Colleges

The CSS Profile is more detailed than FAFSA and is required by most highly selective private colleges in addition to FAFSA. It costs $25 for the first school, $16 for each additional.

Extra documents often required:
- Business/farm supplements (if applicable)
- Non-custodial parent profile (if parents are divorced)
- Prior-prior year AND prior year tax returns

SCHOLARSHIPS

Search Strategies
- Start with your school''s own merit scholarships (often automatic with admission)
- Check your state''s scholarship programs
- Search databases: Fastweb, Scholarships.com, Bold.org
- Ask your employer (or parents'' employers) about scholarship programs
- Look for local community foundation scholarships — less competition

Application Tips
- Create a scholarship tracker spreadsheet: name, amount, deadline, requirements, status
- Reuse essay content across multiple applications when topics overlap
- Apply to small local scholarships — $500–$2,000 awards have far fewer applicants than national ones
- Never pay to apply for a scholarship

